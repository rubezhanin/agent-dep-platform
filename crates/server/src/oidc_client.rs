    /// Build a minimal JWS with the
    /// supplied claims. Header is
    /// `{"alg":"RS256","kid":"k1"}`;
    /// signature is a 256-byte all-zero
    /// buffer (placeholder, since 2.7.7
    /// doesn't verify signatures).
    fn make_jwt(claims: &serde_json::Value) -> String {
        let header = serde_json::json!({"alg": "RS256", "kid": "k1"});
        let header_b64 = base64url(serde_json::to_vec(&header).unwrap().as_slice());
        let payload_b64 = base64url(serde_json::to_vec(claims).unwrap().as_slice());
        let sig_b64 = base64url(&[0u8; 256]);
        format!("{header_b64}.{payload_b64}.{sig_b64}")
    }

