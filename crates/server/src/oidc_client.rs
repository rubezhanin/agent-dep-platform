//! 2.7.7 (ADR-0035) OIDC wire-protocol client.
//!
//! The 2.7.6 framework in `super::oidc` is
//! responsible for the surrounding plumbing
//! (config, state map, role mapping, user
//! provisioning, axum handlers). This module
//! is the *transport* layer: it builds the
//! `/authorize` URL, exchanges the
//! authorization code for tokens, validates
//! the ID token against the JWKS, and
//! extracts claims.
//!
//! Two implementations of [`OidcClient`]:
//! - [`RealOidcClient`]: production. Uses
//!   the `openidconnect` crate + the
//!   `reqwest` async client.
//! - [`MockOidcClient`]: tests + the 2.7.6
//!   `AGENCY_OIDC_MOCK=1` default.
//!
//! The `callback_handler` in `super::oidc`
//! dispatches to whichever is configured.

use std::sync::Arc;

use agent_dep_core::error::{CoreError, CoreResult};
use async_trait::async_trait;
use serde::Deserialize;

use crate::oidc::OidcConfig;

/// What the `/v1/auth/oidc/callback` handler
/// hands to the client to exchange.
#[derive(Debug, Clone)]
pub struct CallbackInput {
    /// The `code` query param from the IdP
    /// redirect.
    pub code: String,
    /// The `state` query param from the IdP
    /// redirect. The 2.7.6 framework has
    /// already validated it against
    /// `OidcPending` and removed the entry.
    /// The PKCE verifier is no longer needed
    /// here — the `RealOidcClient` looks it
    /// up via the state token, but in 2.7.7
    /// we pass the verifier explicitly (the
    /// framework retains the
    /// `(state -> PendingAuth { pkce_verifier,
    /// nonce, ... })` map so the client can
    /// look it up).
    pub state: String,
    /// The PKCE verifier corresponding to
    /// `state`. The 2.7.6 callback handler
    /// pulls this from `OidcPending` before
    /// dropping the entry.
    pub pkce_verifier: String,
    /// The nonce corresponding to `state`.
    pub nonce: String,
}

/// What the client returns on success. The
/// `callback_handler` forwards the claims to
/// `provision_user_from_claims`.
#[derive(Debug, Clone)]
pub struct TokenClaims {
    /// The IdP `sub` claim — the stable
    /// user identifier. Becomes
    /// `users.external_id`.
    pub sub: String,
    /// Optional email.
    pub email: Option<String>,
    /// Optional preferred username.
    pub preferred_username: Option<String>,
    /// The role-claim value (typically
    /// `groups` for Okta / Keycloak /
    /// Auth0). The shape is normalised
    /// upstream by `super::oidc::map_claims_to_role`.
    pub role_claim_value: serde_json::Value,
}

/// 2.7.8 (ADR-0036): what
/// `OidcClient::refresh` returns. The
/// framework re-issues a local bearer
/// token from the new claims and
/// updates `users.token_expires_at`.
#[derive(Debug, Clone)]
pub struct RefreshedTokens {
    pub claims: TokenClaims,
    /// RFC 3339 timestamp at which the
    /// IdP's `access_token` (and the
    /// local bearer) expires. The
    /// framework stores this in
    /// `users.token_expires_at`.
    pub expires_at: String,
    /// New IdP `refresh_token` (if the
    /// IdP rotated it). The framework
    /// does NOT store this (it cannot
    /// keep a 2.x-state-secret); the
    /// SPA holds it client-side.
    pub new_refresh_token: Option<String>,
}

/// The wire-protocol abstraction. Uses
/// `async_trait` for object-safety
/// (so we can store `Arc<dyn OidcClient>`).
#[async_trait]
pub trait OidcClient: Send + Sync {
    /// Build the IdP `/authorize` URL. The
    /// `state` and `code_challenge` are
    /// already generated by the framework;
    /// the client just assembles the URL.
    fn authorize_url(
        &self,
        state: &str,
        code_challenge: &str,
        nonce: &str,
    ) -> CoreResult<String>;

    /// Exchange the authorization code for
    /// tokens, validate the ID token, and
    /// extract claims.
    async fn exchange_code(
        &self,
        input: CallbackInput,
    ) -> CoreResult<TokenClaims>;

    /// 2.7.8 (ADR-0036): refresh the IdP
    /// tokens using the supplied
    /// `refresh_token`. The framework
    /// calls this from the
    /// `POST /v1/auth/oidc/refresh`
    /// endpoint.
    async fn refresh(
        &self,
        refresh_token: &str,
    ) -> CoreResult<RefreshedTokens>;

    /// 2.7.8: build the IdP
    /// `end_session_endpoint` URL (if
    /// published by the IdP's discovery
    /// document). `None` means the IdP
    /// does not support front-channel
    /// logout; the framework's logout
    /// endpoint then returns
    /// `{"message": "logged out locally"}`.
    fn end_session_url(&self) -> CoreResult<Option<String>>;

    /// 2.7.8: downcast to `&dyn Any` so
    /// the framework can read
    /// `RealOidcClient`-specific state
    /// (the cached `end_session_endpoint`)
    /// from inside an `Arc<dyn
    /// OidcClient>`. Returns `&dyn Any`
    /// for the underlying concrete type.
    fn as_any(&self) -> &dyn std::any::Any;
}

